const fs=require("node:fs"),assert=require("node:assert/strict"),path=require("node:path");
const html=fs.readFileSync(path.join(__dirname,"..","index.html"),"utf8");
const app=fs.readFileSync(path.join(__dirname,"..","app.js"),"utf8");
const css=fs.readFileSync(path.join(__dirname,"..","styles.css"),"utf8");
const sidebar=html.slice(html.indexOf('<aside class="right-col">'),html.indexOf("</aside>"));
const ids=["eventsSection","changePanel","reviewSection"];
const positions=ids.map(id=>sidebar.indexOf('id="'+id+'"'));
assert(positions.every(i=>i>=0));
assert(positions[0]<positions[1]&&positions[1]<positions[2],"Sidebar must be Events / Changes / Review");
for(const id of ids)assert(new RegExp('<details\\b[^>]*id="'+id+'"[^>]*open').test(sidebar),"Sidebar must be collapsible with open default: "+id);
assert(app.includes('const bases=overlapping.map'),"Preview lacks merged Excel region backgrounds");
assert(app.includes("'+bases+fills+html+'"),"Merged section backing must be painted before individual cell fills");
assert(css.includes(".preview-region.staffing-label"),"Staff labels require bottom positioning");
console.log("PASS: Events → Changes → Review are collapsible; XLSX preview merges cover internal gridlines");
